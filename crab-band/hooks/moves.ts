const keyOf = (costume: string): string => (MOVES[costume] ? costume : 'other')

// An outfit with no routine of its own (a new savvy tier, a typo) dances the plain crab's.
export const routineOf = (costume: string): Routine => MOVES[keyOf(costume)] ?? MOVES.other

const GROUPS = ['dn', 'bd', 'cl', 'cr', 'la', 'lb'] as const
type Group = (typeof GROUPS)[number]

const transformOf = (group: Group, p: Pose): string => {
  if (group === 'dn') return `translate(${p.jx ?? 0}px,${p.jy ?? 0}px) rotate(${p.rot ?? 0}deg) scale(${p.mirror ? -1 : 1},1)`
  if (group === 'bd') return `translate(0,${p.b ?? 0}px)`
  if (group === 'cl' || group === 'cr') {
    const [dx, dy] = p[group] ?? [0, 0]
    return `translate(${dx}px,${dy}px)`
  }
  return `translateY(${p[group] ?? 0}px)`
}

// Where the whole crab turns, as a share of the 30 x 28 frame `dn` fills.
const pivot = ([x, y]: [number, number]): string => `${+((x / 30) * 100).toFixed(3)}% ${+((y / 28) * 100).toFixed(3)}%`

// One outfit's routine as CSS: a keyframe track for each group that moves, held steps on the 4 s
// loop from the drawing's phase (`--d`). Every name carries the outfit (`mv-<outfit>-<group>`) and
// every rule its class, so crabs of different outfits never share a rule, even inlined on one page.
export const routineCss = (costume: string): string => {
  const outfit = keyOf(costume)
  const routine = routineOf(outfit)
  return GROUPS.flatMap(group => {
    const steps: Array<[number, string]> = []
    for (const [second, pose] of routine.keys) {
      const tf = transformOf(group, pose)
      if (steps[steps.length - 1]?.[1] !== tf) steps.push([second, tf])
    }
    if (steps.every(([, tf]) => tf === transformOf(group, {}))) return []
    const name = `mv-${outfit}-${group}`
    const origin = group === 'dn' ? `transform-origin:${pivot(routine.origin)};` : ''
    return [
      keyframes(name, move(steps)),
      `.c-${outfit}.run .${group}{${origin}animation:${name} ${DANCE_SECONDS}s steps(1,end) infinite var(--d,0s)}`,
    ]
  }).join('\n')
}
