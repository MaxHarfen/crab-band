// The dances: each outfit's 4 s routine, as data. A routine poses the crab's groups over the loop:
// the whole crab (`dn`: jx, jy, rot about `origin`, mirror), a squat of the body (`bd`: b), each claw
// (`cl`, `cr`: [dx, dy] on top of the squat) and each leg pair (`la`, `lb`: a lift), in grid units.
// A key holds until the next. A missing field is at rest: 0, false or [0, 0]. `box` is the view that
// holds every frame of the routine, props and all: [x, y, width, height] on the 30 x 28 grid.
//
// The MOVES block is strict JSON between the MOVES:BEGIN and MOVES:END lines, so docs/make_crab_gif.py
// reads the very same routines.

// Every routine, and every prop loop longer than the once-a-second redraw, lasts this long.
export const DANCE_SECONDS = 4

export const pct = (second: number, loop = DANCE_SECONDS): string => `${((second / loop) * 100).toFixed(3)}%`
export const keyframes = (name: string, steps: Array<[number, string]>, loop = DANCE_SECONDS): string =>
  `@keyframes ${name}{${steps.map(([second, rule]) => `${pct(second, loop)}{${rule}}`).join('')}}`
export const move = (steps: Array<[number, string]>): Array<[number, string]> =>
  steps.map(([s, tf]) => [s, `transform:${tf}`])

export type Pose = {
  jx?: number
  jy?: number
  rot?: number
  mirror?: boolean
  b?: number
  cl?: [number, number]
  cr?: [number, number]
  la?: number
  lb?: number
}
export type Routine = { origin: [number, number]; box: [number, number, number, number]; keys: Array<[number, Pose]> }

